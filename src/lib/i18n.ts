const DICTS: Partial<Record<string, Dict>> = { en, am, om };

export function hasFullInterface(lang: string) {
  return lang in DICTS;
}

export function translate(lang: string, key: MsgKey, vars?: Record<string, string | number>) {
  let s = (DICTS[lang] ?? en)[key] || en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
